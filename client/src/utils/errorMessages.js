export const getErrorMessageByCode = (code, fallback = "حدث خطأ غير متوقع.") =>
  errorMessages[code] || fallback;

export const getApiErrorMessage = (error, fallback = "حدث خطأ غير متوقع.") => {
  const code = error?.response?.data?.code;
  const message = error?.response?.data?.message;
  if (code) {
    return getErrorMessageByCode(code, message || fallback);
  }
  return message || fallback;
};
